const builtInMessages: Record<AiEditorBuiltInLocale, AiEditorMessages> = {'zh-CN': zhCN, 'en-US': {}}

/**
 * 轻量国际化服务。
 * 负责合并内置与宿主语言包、切换当前语言，并通知菜单重新渲染文案。
 */
export class AiEditorI18n {
    private locale: AiEditorLocale
    private readonly messages: AiEditorTranslations
    private readonly listeners = new Set<() => void>()

    constructor(locale: AiEditorLocale = 'zh-CN', translations: AiEditorTranslations = {}) {
        this.locale = locale
        // 自定义语言包覆盖同 locale 的内置键，但不会清除未被覆盖的内置翻译。
        this.messages = Object.fromEntries([
            ...Object.entries(builtInMessages),
            ...Object.entries(translations),
        ].map(([key, messages]) => [key, {
            ...(builtInMessages[key as AiEditorBuiltInLocale] ?? {}),
            ...messages,
        }]))
    }

    getLocale(): AiEditorLocale {
        return this.locale
    }

    /** 切换语言；相同 locale 不重复通知，避免无意义地重建工具栏。 */
    setLocale(locale: AiEditorLocale): void {
        if (locale === this.locale) return
        this.locale = locale
        this.listeners.forEach((listener) => listener())
    }

    /** 翻译源文案；当前语言未配置该键时直接返回源文案。 */
    t(source: string): string {
        return this.messages[this.locale]?.[source] ?? source
    }

    /** 订阅语言变化，并返回幂等的取消订阅函数。 */
    subscribe(listener: () => void): () => void {
        this.listeners.add(listener)
        return () => this.listeners.delete(listener)
    }
}
