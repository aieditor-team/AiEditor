    BackgroundColorMenuItem,
    CodeBlockMenuItem,
    DetailsMenuItem,
    EmojiMenuItem,
    HighlightBlockMenuItem,
    HorizontalRuleMenuItem,
    ImageMenuItem,
    InlineCodeMenuItem,
    FontFamilyMenuItem,
    FontColorMenuItem,
    FontSizeMenuItem,
    FormulaMenuItem,
    FormatPainterMenuItem,
    FullscreenMenuItem,
    HighlightColorMenuItem,
    DecreaseIndentMenuItem,
    IncreaseIndentMenuItem,
    LetterSpacingMenuItem,
    LineHeightMenuItem,
    ItalicMenuItem,
    LinkMenuItem,
    OrderedListMenuItem,
    PasteMenuItem,
